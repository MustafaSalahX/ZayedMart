const AUTO_RTL_MIRROR = new Set(['logout', 'send', 'sidebar']);

/**
 * Human-Crafted Vector Icon System backed by tree-shaken `@phosphor-icons/react`.
 * Defaults to clean `regular` strokes (SF Symbols / Linear refinement), with `filled`,
 * `duotone`, RTL directional mirroring, and safe fallback.
 */
export default function Icon({
  name = '',
  size = 18,
  weight,
  filled = false,
  duotone = false,
  spin = false,
  mirrorRtl,
  className = '',
  ariaLabel,
  title,
  ...rest
}) {
  const Comp = ICON_REGISTRY[name] || Circle;
  const resolvedWeight = weight || (duotone ? 'duotone' : filled ? 'fill' : 'regular');
  const shouldMirror =
    mirrorRtl !== false && (Boolean(mirrorRtl) || AUTO_RTL_MIRROR.has(name));

  return (
    <Comp
      size={size}
      weight={resolvedWeight}
      aria-hidden={ariaLabel ? undefined : true}
      aria-label={ariaLabel || undefined}
      title={title}
      className={`shrink-0 ${shouldMirror ? 'rtl:-scale-x-100' : ''} ${
        spin ? 'animate-spin' : ''
      } ${className}`.trim()}
      {...rest}
    />
  );
}
